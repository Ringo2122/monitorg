# encoding: utf-8
module Vat
  module_function

  NO = /НДС[^.;]{0,40}?не\s*облага|не\s*облага\S*\s+НДС|НДС\s+не\s+взима|сверху\s+не\s+(?:начисля|добавля)|не\s+является\s+плательщик\S*\s+НДС|освобожд\S*\s+от\s+(?:уплаты\s+)?НДС/i
  ADD = /плюс\s*(?:\d+\s*%\s*)?НДС|\+\s*НДС|НДС\s+(?:начисляется|уплачивается|оплачивается)\s+сверх|будет\s+(?:добавлен|начислен)\S*\s+НДС|без\s+уч[её]та\s+НДС\s*\(\s*НДС\s*\d+\s*%\s*\)/i
  MAY = /увелич\S*\s+на\s+(?:сумму\s+)?(?:\d+\s*%\s*)?НДС|наличие\s+или\s+отсутствие\s+НДС|исчисляем\S*\s+сверх|без\s+(?:уч[её]та\s+)?НДС/i
  IN_TEXT = /(?:цен\S*|стоимост\S*|ставк\S*|указан\S*|прода[её]т\S*|реализ\S*)(?:[^.;]|\.\d){0,40}?[сc]\s+(?:уч[её]т\S*\s+)?(?:\d+\s*%\s*)?НДС|\(\s*[сc]\s+(?:уч[её]т\S*\s+)?НДС|(?:включая|в\s+том\s+числе|включа\S*)\s+НДС|НДС\s+включ[её]н/i
  IN_FIELD = /[сc]\s+(?:уч[её]т\S*\s+)?(?:\d+\s*%\s*)?НДС|включ/i

  def kind(terms, text)
    f = terms['vat'].to_s
    d = text.to_s
    return 'no' if f =~ NO || d =~ NO
    return 'add' if f =~ ADD || d =~ ADD
    return 'may' if terms['vat_add'] || f =~ MAY || d =~ MAY
    return 'in' if f =~ IN_FIELD || d =~ IN_TEXT
    nil
  end
end
