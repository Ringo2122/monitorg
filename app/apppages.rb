  def para(t)
    t.to_s.split(/\n{2,}/).map { |p| "<p>#{h(p.strip).gsub("\n", '<br>')}</p>" }.join
  end

  def app_page(path, title, desc, body, ld = [])
    f = File.join(@out, '_p', "#{path.sub(%r{\A/}, '')}.html")
    FileUtils.mkdir_p(File.dirname(f))
    desc = desc[0, 167].sub(/[\s,;:–—-]+\S*\z/, '') + '…' if desc.size > 170
    robots = @live ? 'index, follow' : 'noindex, nofollow'
    File.write(f, @shell.(title: title, desc: desc, path: path, robots: robots, ld: ld, route: path, main: body))
    @sitemap << [path, mark(path, [title, desc, robots, JSON.generate(ld), body])]
    @n += 1
  end

  def app_pages(cfg)
    APP_PAGES.each do |path, pg|
      cr, ld_b = crumbs([[pg[:h1], nil]])
      body = %(<div class="wrap">#{cr}<div class="cat-head"><h1>#{h(pg[:h1])}</h1>#{pg[:intro] ? %(<p class="lede">#{h(pg[:intro])}</p>) : ''}</div>) +
             pg[:sec].map { |hd, tx| %(<section class="sec"><h2>#{h(hd)}</h2><p>#{h(tx)}</p></section>) }.join +
             %(<section class="sec seo-links"><ul>#{pg[:links].map { |t, u| %(<li><a href="#{u}">#{h(t)}</a></li>) }.join}</ul></section></div>)
      app_page(path, pg[:title], pg[:desc], body, [ld_b])
    end
    news = Array(cfg['news']).select { |n| n['slug'].to_s =~ /\A[a-z0-9-]+\z/ }.sort_by { |n| n['date'].to_s }.reverse
    if news.any?
      cr, ld_b = crumbs([['Новости', nil]])
      list = news.map { |n| %(<li><a href="/news/#{n['slug']}">#{h(n['title'])}</a> <small>#{h(rdate(n['date']))}</small><p>#{h(n['lead'])}</p></li>) }.join
      app_page('/news', 'Новости о торгах и аукционах в Беларуси | МониТорг',
               "Новости МониТорга: #{news.first(2).map { |n| n['title'] }.join('; ')}.",
               %(<div class="wrap">#{cr}<div class="cat-head"><h1>Новости</h1></div><ul class="news-l">#{list}</ul></div>), [ld_b])
      news.each do |n|
        cr, ld_b = crumbs([['Новости', '/news'], [n['title'], nil]])
        src = n['src'].to_s =~ %r{\Ahttps?://} ? %(<p>Источник: <a href="#{h(n['src'])}" rel="nofollow noopener">#{h(n['srcName'].to_s.empty? ? n['src'] : n['srcName'])}</a></p>) : ''
        art = { '@context' => 'https://schema.org', '@type' => 'NewsArticle', 'headline' => n['title'].to_s[0, 110],
                'datePublished' => n['date'].to_s, 'description' => n['lead'].to_s, 'mainEntityOfPage' => "#{SITE}/news/#{n['slug']}",
                'publisher' => { '@type' => 'Organization', 'name' => 'МониТорг' } }
        app_page("/news/#{n['slug']}", "#{n['title']} | МониТорг", n['lead'].to_s.empty? ? n['title'].to_s : n['lead'].to_s,
                 %(<div class="wrap">#{cr}<article><h1>#{h(n['title'])}</h1><p><small>#{h(rdate(n['date']))}</small></p><p class="lede">#{h(n['lead'])}</p>#{para(n['body'])}#{src}</article></div>),
                 [ld_b, art])
      end
    end
    { '/privacy' => ['privacy_text', 'Политика конфиденциальности'], '/cookies' => ['cookie_policy', 'Политика cookie'] }.each do |path, (k, name)|
      t = (cfg['texts'] || {})[k].to_s.strip
      next if t.empty?
      lines = t.lines.map(&:strip).reject(&:empty?)
      lines.shift if lines.first.to_s.casecmp?(name)
      cr, ld_b = crumbs([[name, nil]])
      app_page(path, "#{name} | МониТорг", "#{name} сайта МониТорг (monitorg.by): какие данные обрабатываются, зачем, сколько хранятся и как отозвать согласие.",
               %(<div class="wrap">#{cr}<h1>#{h(name)}</h1>#{lines.map { |x| "<p>#{h(x)}</p>" }.join}</div>), [ld_b])
    end
  end

  def rdate(s)
    y, m, d = s.to_s.split('-').map(&:to_i)
    return s.to_s unless d && d.positive?
    "#{d} #{%w[января февраля марта апреля мая июня июля августа сентября октября ноября декабря][m - 1]} #{y}"
  end
